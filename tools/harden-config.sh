#!/bin/bash
# max-opsec profile, applied to a COPY (.config.hardened). your real .config is never touched.
# default KEEP keeps 32-bit + Wine support, hardened (see tools/hollow-cmdline.txt)
set -e
T=${T:-$HOME/src/linux-hollow}
C=$T/.config.hardened
cp "$T/.config" "$C"
S="$T/scripts/config --file $C"
MK="make -C $T KCONFIG_CONFIG=.config.hardened"
command -v clang >/dev/null && command -v ld.lld >/dev/null && MK="$MK LLVM=1" && CLANG=1

ON="EXPERT IA32_RUNTIME_GATE GCC_PLUGINS KSTACK_ERASE GCC_PLUGIN_LATENT_ENTROPY RANDSTRUCT_FULL UBSAN UBSAN_BOUNDS UBSAN_TRAP
    EFI_DISABLE_PCI_DMA INIT_ON_FREE_DEFAULT_ON MITIGATION_SLS PAGE_TABLE_CHECK PAGE_TABLE_CHECK_ENFORCED
    PANIC_ON_OOPS STRICT_DEVMEM IO_STRICT_DEVMEM BPF_JIT_ALWAYS_ON BPF_UNPRIV_DEFAULT_OFF
    DEBUG_FS_ALLOW_NONE LEGACY_VSYSCALL_NONE
    LOCK_DOWN_KERNEL_FORCE_CONFIDENTIALITY SECURITY_LOADPIN STATIC_USERMODEHELPER TRIM_UNUSED_KSYMS"
[ -n "$CLANG" ] && ON="$ON CFI"

OFF="IA32_EMULATION_DEFAULT_DISABLED ACPI_APEI_EINJ BLK_DEV_IO_TRACE BPF_EVENTS EFI_TEST FW_LOADER_USER_HELPER HWPOISON_INJECT KALLSYMS_ALL
     MEM_SOFT_DIRTY MMIOTRACE MODULE_FORCE_LOAD MODULE_FORCE_UNLOAD PTDUMP_DEBUGFS EFI_PGT_DUMP SLAB_MERGE_DEFAULT
     X86_16BIT X86_DEBUG_FPU X86_MCE_INJECT X86_VSYSCALL_EMULATION KPROBES UPROBES FTRACE FUNCTION_TRACER
     MAGIC_SYSRQ INET_DIAG KSTACK_ERASE_METRICS KSTACK_ERASE_RUNTIME_DISABLE
     BINFMT_MISC BPF_SYSCALL COMPAT COREDUMP DEBUG_FS IA32_EMULATION IO_URING KSM MODIFY_LDT_SYSCALL
     PROC_PAGE_MONITOR PROFILING USERFAULTFD X86_CPUID X86_IOPL_IOPERM X86_MSR"

KEEP=${KEEP-"IA32_EMULATION COMPAT MODIFY_LDT_SYSCALL"}
OFF=$(echo $OFF)
for k in $KEEP; do OFF=$(echo " $OFF " | sed "s/ $k / /"); done

apply() {
    for o in $ON; do $S -e "$o"; done
    for o in $OFF; do $S -d "$o"; done
    $S --set-str STATIC_USERMODEHELPER_PATH /sbin/usermode-helper
}

apply
$MK olddefconfig
apply            # second pass: re-assert anything olddefconfig resolved back
$MK olddefconfig
echo "done: $C"
